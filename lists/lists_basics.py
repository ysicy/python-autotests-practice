# Основы работы со списками
print("=== Создание и работа со списками ===")

# Создание списков
students = ["Анна", "Иван", "Мария", "Петр"]
grades = [5, 4, 5, 3]
subjects = ["математика", "физика", "химия", "биология"]

print("Исходные списки:")
print(f"Студенты: {students}")
print(f"Оценки: {grades}")
print(f"Предметы: {subjects}")

# Получение информации о списке
print(f"\nИнформация о списках:")
print(f"Количество студентов: {len(students)}")
print(f"Количество оценок: {len(grades)}")

# Доступ к элементам по индексу
print(f"\nДоступ к элементам:")
print(f"Первый студент: {students[0]}")
print(f"Последний студент: {students[-1]}")
print(f"Вторая оценка: {grades[1]}")

# Изменение элементов
print(f"\nИзменение элементов:")
print(f"До изменения: {subjects}")
subjects[0] = "алгебра"  # Заменяем "математика" на "алгебра"
print(f"После изменения: {subjects}")

# Проверка наличия элемента в списке
print(f"\nПроверка наличия элементов:")
has_anna = "Анна" in students
has_sergey = "Сергей" in students
print(f"Есть студент 'Анна': {has_anna}")
print(f"Есть студент 'Сергей': {has_sergey}")