# Работа с готовыми списками данных
print("=== Работа с готовыми списками ===")

# Список студентов класса
students = ["Анна", "Иван", "Мария", "Петр", "Елена"]
print(f"Студенты класса: {students}")
print(f"Количество студентов: {len(students)}")

# Список оценок за контрольную
grades = [5, 4, 5, 3, 4]
print(f"Оценки за контрольную: {grades}")

# Работаем с конкретными студентами и оценками
print(f"\nИнформация по студентам:")
print(f"Студент {students[0]} получил оценку {grades[0]}")
