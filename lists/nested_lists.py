# Получаем части списка (срезы)
print(f"\nРабота со срезами:")
first_three_students = students[0:3]
print(f"Первые три студента: {first_three_students}")

last_two_students = students[-2:]
print(f"Последние два студента: {last_two_students}")

# Список дней недели
weekdays = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
