# Простой список внутри списка (координаты точек)
point1 = [10, 20]  # x=10, y=20
point2 = [30, 40]  # x=30, y=40
point3 = [50, 60]  # x=50, y=60

points = [point1, point2, point3]
print(f"\nСписок точек: {points}")

# Получаем координаты первой точки
print(f"Координаты первой точки: x={points[0][0]}, y={points[0][1]}")
print(f"Координаты второй точки: x={points[1][0]}, y={points[1][1]}")

# Меняем координату
points[0][0] = 15  # Меняем x первой точки с 10 на 15
print(f"После изменения: {points}")

# Простая таблица - список товаров с ценами
products = [
    ["Хлеб", 30],
    ["Молоко", 60],
    ["Яйца", 80]
]

print(f"\nТовары и цены:")
print(f"{products[0][0]} - {products[0][1]} рублей")
print(f"{products[1][0]} - {products[1][1]} рублей")
print(f"{products[2][0]} - {products[2][1]} рублей")

# Считаем общую стоимость
total_cost = products[0][1] + products[1][1] + products[2][1]
